import assert from "node:assert/strict";
import { randomBytes } from "node:crypto";
import { resolve } from "node:path";
import { newAccessCredential } from "../client/commands.ts";

export async function checkAgentApkAccess({ host, android: initial, command, call, request, ok, error, report, restart, close, checkpoint, phoneNow, waitForExpiry }) {
  let android = initial;
  const id = () => randomBytes(16).toString("hex");
  const space = id(), hidden = id(), column = id(), card = id();
  const title = "Phone only before exchange";
  const owner = (operation, parameters) => command(android, operation, parameters);
  ok(owner("space.create", { space, name: "Agent APK access" }));
  ok(owner("space.create", { space: hidden, name: "Private phone space" }));
  ok(owner("column.create", { space, column, name: "Local phone column" }));
  ok(owner("card.create", { space, column, card, title, description: "Локальные данные телефона 😀" }));
  const privateBefore = ok(owner("space.read", { space: hidden }));
  const hostBefore = ok(command(host, "space.list", { include_trashed: true }));
  assert.ok(!hostBefore.spaces.some(item => [space, hidden].includes(item.space)), "Phone data was already synchronized");
  const enrollment = await newAccessCredential();
  async function target(material) {
    const keyFile = resolve(report, `agent-${id()}.key`);
    await Bun.write(keyFile, material.credential.key);
    return { ...android, keyFile };
  }
  let agent = await target(enrollment);
  const send = (operation, parameters) => command(agent, operation, parameters);
  const read = () => ok(send("card.read", { space, card }));
  const intent = request("card.read", { space, card });
  error(call(agent, "card.read", intent), "access_denied");
  await checkpoint("defaults", { space, card, subject: enrollment.credential.subject, verifier: Buffer.from(enrollment.verifier).toString("hex") });
  error(call(agent, "card.read", intent), "access_denied");
  const registration = { subject: enrollment.credential.subject, verifier: enrollment.verifier, scope: { kind: "spaces", spaces: { [space]: "read" } }, expires_at_unix_ms: null };
  const issued = ok(owner("access.issue", registration));
  assert.deepEqual(issued.scope, registration.scope);
  assert.equal(issued.expires_at_unix_ms, null);
  const before = read();
  assert.deepEqual(before.titles, [title]);
  assert.deepEqual(before.descriptions, ["Локальные данные телефона 😀"]);
  assert.deepEqual(ok(call(agent, "card.read", intent)), before);
  assert.deepEqual(ok(send("space.list", { include_trashed: true })).spaces.map(item => item.space), [space]);
  for (const inaccessible of [hidden, id()]) error(send("space.read", { space: inaccessible }), "access_denied");
  error(send("card.edit", { space, card, title: "Denied", description: "", expected: before.version }), "access_denied");
  error(send("access.list", { after: null }), "access_denied");
  error(send("access.issue", { ...registration, subject: id() }), "access_denied");
  const verifier = await target({ credential: { key: Buffer.from(enrollment.verifier).toString("hex") } });
  error(command(verifier, "space.read", { space }), "access_denied");
  android = await restart(); agent = { ...agent, ...android, keyFile: agent.keyFile };
  assert.deepEqual(read(), before, "Phone data changed on process restart");
  assert.equal(call(agent, "card.read", intent).replayed, true);
  const writable = await newAccessCredential();
  const changed = ok(owner("access.replace", { ...registration, verifier: writable.verifier, scope: { kind: "spaces", spaces: { [space]: "read_write" } }, expected: issued.version }));
  error(call(agent, "card.read", intent), "access_denied");
  agent = await target(writable);
  const edit = request("card.edit", { space, card, title: "Written directly from PC", description: before.descriptions[0], expected: before.version });
  const edited = ok(call(agent, "card.edit", edit));
  assert.equal(call(agent, "card.edit", edit).replayed, true);
  assert.deepEqual(ok(owner("card.read", { space, card })), edited);
  error(send("card.edit", { ...edit.parameters, title: "Stale write" }), "stale_state");
  error(send("access.list", { after: null }), "access_denied");
  error(send("space.read", { space: hidden }), "access_denied");
  await checkpoint("remote-write", { space, card, title: "Written directly from PC", localTitle: "Edited on phone" });
  if (process.env.P06_AGENT_UI === "1") assert.deepEqual(read().titles, ["Edited on phone"], "Local IPC edit not visible to remote agent");
  const current = read();
  ok(send("card.edit", { space, card, title, description: before.descriptions[0], expected: current.version }));
  const trashed = ok(send("card.trash", { space, card, expected: read().version }));
  assert.equal(trashed.state, "trashed");
  const restored = ok(send("card.restore", { space, card, expected: trashed.version }));
  assert.equal(restored.state, "active");
  assert.deepEqual(restored.titles, [title]);
  const history = ok(send("card.history", { space, card, after: null, limit: 50, expected: null }));
  close();
  error(send("card.read", { space, card }), "unavailable");
  android = await restart(); agent = { ...android, keyFile: agent.keyFile };
  assert.deepEqual(read(), restored);
  assert.deepEqual(ok(send("card.history", { space, card, after: null, limit: 50, expected: null })), history);
  await checkpoint("restarted", { space, card, title });
  const revokedRead = request("card.read", { space, card });
  ok(call(agent, "card.read", revokedRead));
  ok(owner("access.revoke", { subject: registration.subject, expected: changed.version }));
  error(call(agent, "card.read", revokedRead), "access_denied");
  error(call(agent, "card.edit", edit), "access_denied");
  const timed = await newAccessCredential();
  const expires = phoneNow() + 10000;
  const revoked = ok(owner("access.inspect", { subject: registration.subject }));
  const limited = ok(owner("access.replace", { ...registration, verifier: timed.verifier, expires_at_unix_ms: expires, expected: revoked.version }));
  agent = await target(timed);
  const timedRead = request("card.read", { space, card });
  ok(call(agent, "card.read", timedRead));
  await waitForExpiry(expires);
  await Bun.write(resolve(report, 'agent-expiry-clock.json'), JSON.stringify({ expires, phone: phoneNow(), host: Date.now() }));
  error(call(agent, "card.read", timedRead), "access_denied");
  error(send("card.read", { space, card }), "access_denied");
  android = await restart(); agent = { ...android, keyFile: agent.keyFile };
  error(call(agent, "card.read", timedRead), "access_denied");
  const renewed = await newAccessCredential();
  ok(owner("access.replace", { ...registration, verifier: renewed.verifier, expected: limited.version }));
  error(call(agent, "card.read", timedRead), "access_denied");
  agent = await target(renewed);
  assert.deepEqual(read(), restored);
  assert.deepEqual(ok(owner("space.read", { space: hidden })), privateBefore);
  assert.deepEqual(ok(command(host, "space.list", { include_trashed: true })), hostBefore, "Direct access synchronized phone data to PC");
  const last = ok(owner("access.inspect", { subject: registration.subject }));
  ok(owner("access.revoke", { subject: registration.subject, expected: last.version }));
  error(send("card.read", { space, card }), "access_denied");
  console.log("Direct PC → APK agent: own scoped key, unsynchronized phone data, read/write/stale/replay, reverse/trash/restore, expiry/revoke/regrant, process restart and unavailable passed.");
}
